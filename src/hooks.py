CATEGORIES = list(HOOK_TEMPLATES.keys())

# 開頭鉤子原則（寫進腳本框架備註）
HOOK_RULES = [
    "符合人性：懶、貪",
    "要短：10–15 字內",
    "要狠：有情緒、引發共鳴",
    "要直：直接點痛點或結果",
    "創造期待感",
]


def pick_diverse(n, used_categories=None):
    """挑 n 個 (類別, 模板)，盡量分屬不同類別。
    used_categories: 最近用過的類別，優先避開。
    回傳 list[(category, template)]。
    """
    used = set(used_categories or [])
    order = [c for c in CATEGORIES if c not in used] + [c for c in CATEGORIES if c in used]
    out = []
    ci = 0
    for i in range(n):
        # 盡量每支換一個類別
        cat = order[ci % len(order)]
        ci += 1
        tmpl = HOOK_TEMPLATES[cat][i % len(HOOK_TEMPLATES[cat])]
        out.append((cat, tmpl))
    return out
